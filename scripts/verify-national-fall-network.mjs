import assert from 'node:assert/strict';
import fs from 'node:fs';

const html=fs.readFileSync('public/synced-national-tools/index.html','utf8');
const css=fs.readFileSync('public/synced-national-tools/assets/fall-color-network.css','utf8');
const section=html.match(/<!-- national-fall-network:start -->([\s\S]*?)<!-- national-fall-network:end -->/);
assert.ok(section, 'featured fall network exists');
const markup=section[1];
const hrefs=[...markup.matchAll(/href="([^"]+)"/g)].map(x=>x[1]);
const regions=hrefs.filter(x=>/^\/fall-color\/(new-england|great-smoky-mountains|colorado-aspens|adirondacks|north-shore-superior|ozarks|eastern-sierra|wasatch|columbia-river-gorge|door-county|poconos|texas-hill-country|west-virginia-highlands|catskills|shenandoah)\/$/.test(x));
const destinations=hrefs.filter(x=>/^\/fall-color\/[^/]+\/[^/]+\/$/.test(x));
assert.equal(regions.length,15,'15 distinct direct regional links');
assert.equal(new Set(regions).size,15,'unique regional paths');
assert.equal(destinations.length,4,'four featured destination guides');
assert.ok(hrefs.includes('/fall-color/national/'), 'map and complete 30-place network available');
assert.ok(markup.includes('30 named destination guides'));
assert.ok(markup.includes('data-search-card')&&markup.includes('data-catalog-group'),'search and season filters support network');
assert.ok(!markup.includes('target="_blank"'),'internal navigation stays in same tab');
assert.ok(css.includes('@media(max-width:620px)'), 'mobile breakpoint');
assert.ok(html.includes('href="/national-tools/assets/fall-color-network.css?v=20261009-1"'),'stylesheet served');
assert.equal((html.match(/<!-- national-fall-network:start -->/g)||[]).length,1,'no duplicate sections');
const found=html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
assert.ok(found);
const graph=JSON.parse(found[1])['@graph'];
const list=graph.find(x=>x['@id']==='https://chrisizworski.com/national-tools/#toollist');
const regionList=graph.find(x=>x['@id']==='https://chrisizworski.com/national-tools/#fall-network-regions');
const page=graph.find(x=>x['@id']==='https://chrisizworski.com/national-tools/#page');
assert.equal(list.numberOfItems,(html.match(/data-search-card/g)||[]).length, 'searchable card count equals schema count');
assert.equal(list.itemListElement.filter(x=>x.url==='https://chrisizworski.com/fall-color/national/').length,1,'one canonical map directory entry');
assert.equal(regionList.itemListElement.length,15);
assert.equal(page.dateModified,'2026-10-09');
assert.equal(new Set(regionList.itemListElement.map(x=>x.url)).size,15);
console.log('NATIONAL_FALL_NETWORK_PASS — 15 regions, 4 featured destinations, all 30 linked through hub; directory schema and filters intact');
