#!/usr/bin/env node
// Convert the pinned rustc WASM build to a UTF-8 ESM payload for Vercel.
// This is real compiler output, never a JS reimplementation of the binary.
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const wasmArg=process.argv.find(a=>a.startsWith('--wasm='));
if(!wasmArg)throw Error('Usage: node scripts/build-snowmobile-rust.cjs --wasm=/path/snowmobile.wasm');
const wasm=fs.readFileSync(wasmArg.slice(7));
if(wasm.subarray(0,4).toString('hex')!=='0061736d')throw Error('Input is not WebAssembly');
const asset=path.join(__dirname,'../lib/snowmobile/rust-binary.mjs');
const output='// Generated by .github/workflows/snowmobile-rust-wasm.yml from pinned Rust 1.90.0.\n'+
  '// Do not edit manually: test byte-for-byte parity against rustc output.\n'+
  'export const WASM_BASE64 = '+JSON.stringify(wasm.toString('base64'))+';\n';
fs.writeFileSync(asset,output);
console.log('Compiled Rust/WASM asset generated:',wasm.length,'bytes');
