 assert.deepEqual(near.counts,{curated:78,eligible:69,excluded:9});
 const x=near.locations.find(x=>x.id==='middle-hungarian-falls');
 assert.ok(x);
 assert.deepEqual([x.lat,x.lng],[47.17193,-88.44781]);
 assert.ok(!near.excludedIds.includes(x.id));
 assert.equal(near.nearby[x.id][0].id,'upper-hungarian-falls');
