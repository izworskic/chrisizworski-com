test('B76 new middle fall is GIS-identity honest, KLT public access is source-backed on all five axes',()=>{
 const x=cat.waterfalls.find(row=>row.id==='middle-hungarian-falls');
 assert.ok(x);
 assert.equal(x.gisObjectId,null);
 assert.equal(x.publication,'verified-access-guide');
 assert.equal(x.status,'verify');
 assert.deepEqual([x.lat,x.lng],[47.17193,-88.44781]);
 for(const axis of ['landManager','publicAccess','parking','trail','location']){
   assert.equal(x.verification[axis].verified,true,axis);
   assert.ok(x.verification[axis].source.startsWith('https://'),axis);
 }
 assert.equal(x.geocodeProvenance.notOfficialFallsSurvey,true);
 assert.equal(x.geocodeProvenance.notParking,true);
 assert.equal(x.geocodeProvenance.notTrailRoute,true);
 assert.deepEqual([cat.waterfalls.length,rec.counts.curatedTotal,led.curatedCount,queue.counts.curatedDestinations],[78,78,78,78]);
 assert.deepEqual([rec.counts.exactIdMatched,rec.counts.pending,rec.counts.curatedNoMatchingGIS],[69,92,13]);
 assert.ok(rec.curatedWithoutExactGISMatch.some(row=>row.id===x.id&&row.gisObjectId===null));
 assert.ok(led.entries.some(row=>row.curatedId===x.id&&row.sourceId===null&&row.coordinateRole==='independent-waterfall-feature-not-parking-or-trailhead'));
 const top=rec.candidates.find(row=>row.gisObjectId===134);
 const bottom=rec.candidates.find(row=>row.gisObjectId===130);
 assert.equal(top.curatedId,'upper-hungarian-falls');
 assert.equal(bottom.curatedId,'lower-hungarian-falls');
});
test('B76 middle guide, hub and sitemap add exactly one distinct indexable waterfall',()=>{
 assert.match(guide,/<meta name="robots" content="index,follow/);
 assert.match(guide,/rel="canonical" href="https:\/\/chrisizworski.com\/upper-peninsula-waterfalls\/middle-hungarian-falls\//);
 assert.match(guide,/https:\/\/chrisizworski.com\/#person/);
 const title=(guide.match(/<title>([^<]+)<\/title>/)||[])[1];
 const desc=(guide.match(/<meta name="description" content="([^"]+)"/)||[])[1];
 assert.ok(title.length<=60,title);
 assert.ok(desc.length<=158,desc);
 assert.match(guide,/current conditions unverified/i);
 assert.match(guide,/data-lat="47.17193" data-lng="-88.44781"/);
 assert.match(guide,/data-parking-lat="47.173159" data-parking-lng="-88.444743"/);
 assert.match(guide,/not a validated trailhead|not a surveyed KLT viewpoint/i);
 assert.match(guide,/Middle Falls/);
 assert.match(hub,/data-id="middle-hungarian-falls"/);
 assert.match(hub,/data-parking-lat="47.173159" data-parking-lng="-88.444743"/);
 assert.match(hub,/78 curated visitor destinations/);
 assert.match(hub,/78 curated waterfall profiles/);
 for(const id of ['upper-hungarian-falls','lower-hungarian-falls']){
   assert.match(read('public/upper-peninsula-waterfalls/'+id+'/index.html'),/href="\/upper-peninsula-waterfalls\/middle-hungarian-falls\/"/);
 }
 assert.match(guide,/href="\/upper-peninsula-waterfalls\/upper-hungarian-falls\/"/);
 assert.match(guide,/href="\/upper-peninsula-waterfalls\/lower-hungarian-falls\/"/);
 const m=hub.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
 const graph=JSON.parse(m[1])['@graph'];const list=graph.find(x=>x['@type']==='ItemList');
 assert.equal(list.numberOfItems,76);
 assert.equal(list.itemListElement.length,76);
 assert.equal(list.itemListElement.filter(x=>x.name==='Middle Hungarian Falls').length,1);
 assert.equal((sitemap.match(/<loc>/g)||[]).length,76);
 assert.match(sitemap,/middle-hungarian-falls\/<\/loc><lastmod>2026-11-07/);
});
