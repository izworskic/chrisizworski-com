'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),cp=require('node:child_process');
const read=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const e=JSON.parse(read('data/up-waterfall-b75-boston-creek-online-evidence.json'));
const c=JSON.parse(read('data/up-waterfalls.json'));
const rec=JSON.parse(read('data/up-waterfall-reconciliation.json'));
const led=JSON.parse(read('data/up-waterfall-inventory-ledger.json'));
const q=JSON.parse(read('data/up-waterfall-review-queue.json'));
const near=JSON.parse(read('public/assets/up-waterfalls-nearby.json'));
const hub=read('public/upper-peninsula-waterfalls/index.html');
const guide=read('public/upper-peninsula-waterfalls/boston-creek-cascades/index.html');
const sitemap=read('public/sitemap-up-waterfalls.xml');
test('B75 owner-published public loop and separate preserve map role',()=>{
 assert.equal(e.batch,'B75');
 assert.equal(e.reviewDate,'2026-11-06');
 assert.equal(e.noOutreach,true);
 const f=e.featuredDestination;
 assert.equal(f.namedWaterfall,false,'do not invent a separately named cascade');
 assert.equal(f.verifiedExactCascadeCoordinates,false);
 assert.equal(f.verifiedParkingCoordinate,false);
 assert.equal(f.namedTrailGeometryAvailable,false);
 assert.equal(f.trailLoopMiles,0.8);
 assert.equal(f.parkingPointLocationVerified,undefined);
 assert.equal(f.natureAreaCenter.osmRelation,21118953);
 assert.deepEqual([f.natureAreaCenter.lat,f.natureAreaCenter.lng],[47.1832201,-88.5711361]);
 assert.equal(f.natureAreaCenter.exactPointForDriving,false);
 assert.equal(f.routeToMapCenter,false);
 assert.equal(f.routeToNaturalCascade,false);
 assert.equal(f.publicationEligible,true);
 assert.match(f.landManagerSource,/keweenawlandtrust.org/);
});
test('B75 curated Boston public nature trail changes only non-GIS inventory',()=>{
 const x=c.waterfalls.find(r=>r.id==='boston-creek-cascades');
 assert.ok(x);
 assert.equal(x.gisObjectId,null);
 assert.equal(x.mapRole,'preserve-centre');
 assert.equal(x.nearbyExcluded,true);
 assert.equal(x.publication,'verified-access-guide');
 assert.equal(x.manager,'Keweenaw Land Trust');
 assert.equal(x.verification.landManager.verified,true);
 assert.equal(x.verification.publicAccess.verified,true);
 assert.equal(x.verification.parking.verified,true);
 assert.equal(x.verification.trail.verified,true);
 assert.match(x.verification.location.description,/NOT waterfall location/);
 assert.deepEqual([c.waterfalls.length,rec.counts.curatedTotal,led.curatedCount,q.counts.curatedDestinations],[78,78,78,78]);
 assert.deepEqual([rec.counts.exactIdMatched,rec.counts.pending,rec.counts.curatedNoMatchingGIS],[69,92,13]);
 assert.equal(led.linkedByExactOid,69);
 assert.equal(q.counts.pendingGisFeatures,92);
 assert.ok(rec.curatedWithoutExactGISMatch.some(r=>r.id===x.id));
 assert.ok(led.entries.some(r=>r.curatedId===x.id&&r.source==='curated-non-gis'&&r.coordinateRole.includes('not-natural-falls')));
});
test('B75 map never makes the reserve centre a waterfall/trailhead/parking coordinate',()=>{
 assert.match(hub,/data-id="boston-creek-cascades"/);
 assert.match(hub,/data-point-role="preserve-centre"/);
 assert.match(hub,/78 curated visitor destinations/);
 assert.match(hub,/78 curated waterfall profiles/);
 assert.match(guide,/<meta name="robots" content="index,follow,max-image-preview:large">/);
 assert.match(guide,/rel="canonical" href="https:\/\/chrisizworski.com\/upper-peninsula-waterfalls\/boston-creek-cascades\//);
 assert.match(guide,/data-role="preserve-centre"/);
 assert.match(guide,/not a surveyed cascade, trail, or parking lot/);
 assert.match(guide,/Keweenaw Land Trust/);
 assert.match(guide,/0.8-mile loop/);
 assert.match(guide,/~3 spaces/);
 assert.match(guide,/"@type":"TouristDestination"/);
 assert.doesNotMatch(guide,/"@type":"TouristAttraction"/);
 assert.doesNotMatch(guide,/google.com\/maps\/dir|driving_destination/i);
 const mapJs=read('public/assets/up-waterfalls.js');
 assert.match(mapJs,/dataset.pointRole==='preserve-centre'/);
 assert.match(mapJs,/MAP REFERENCE ONLY/);
 const s=JSON.parse((hub.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)||[])[1]);
 const list=s['@graph'].find(v=>v['@type']==='ItemList');
 assert.ok(list);
 assert.equal(list.itemListElement.length,76);
 assert.ok(list.itemListElement.some(v=>v.name==='Boston Creek Cascades (Nature Area)'));
 assert.equal((sitemap.match(/<loc>/g)||[]).length,76);
 assert.match(sitemap,/upper-peninsula-waterfalls\/boston-creek-cascades\//);
});
