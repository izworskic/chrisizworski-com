'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const source=require('../public/rockhounding-lab/photo-free-wave-activity-2026.json');
const season=require('../public/rockhounding-lab/glos-season-2026-research.json');
const html=fs.readFileSync(path.join(__dirname,'../public/rockhounding-lab/index.html'),'utf8');
test('5,243 actual GLOS wave observations give eight scientifically bounded, photo-free activity comparisons',()=>{
 assert.equal(source.schemaVersion,'rockhounding-photo-free-measured-activity-v1');
 assert.equal(source.baseSourceOriginalRows,5243);
 assert.equal(source.episodeTotal,8);
 assert.equal(source.episodesWithSufficientCoverage,8);
 assert.equal(source.meanPeriodIsNotEnergyPeriod,true);
 assert.equal(source.lakewardNormalFromOldNoaaChartNotCurrentBeachSurvey,true);
 assert.equal(source.cannotInferBayshoreHarborFromAgate,true);
 assert.equal(source.snapshotIsDatedArchiveNotLive,true);
 assert.equal(source.sourceObservationEndUTC,'2026-10-14T23:46:01Z');
 assert.equal(source.activityUnit,'relative m^2 * seconds * hours proxy; NOT wave-power kW/m');
 assert.equal(source.gapHoursNotInterpolated,1.5);
 assert.equal(source.canPredictNewStones,false);
 assert.equal(source.canPublishVisitWindow,false);
 assert.equal(source.canClaimSafeAccess,false);
 assert.equal(source.photoEvidenceRequired,false);
 assert.equal(source.harborWaveTransferValidated,false);
});
test('the taller Oct 12 peak is NOT mislabeled strongest prolonged activity; Oct 5 leads measured integral',()=>{
 const oct5=source.entries.find(x=>x.peakAtUTC==='2026-10-05T07:16:01Z');
 const oct12=source.entries.find(x=>x.peakAtUTC==='2026-10-12T14:46:01Z');
 assert.ok(oct5&&oct12);
 assert.equal(oct5.peakSignificantHeightM,2.51);
 assert.equal(oct12.peakSignificantHeightM,2.57);
 assert.equal(oct5.observedWaveActivityProxy,953.898);
 assert.equal(oct12.observedWaveActivityProxy,746.469);
 assert.equal(oct5.relativeToLargestMeasured2026EpisodePct,100);
 assert.equal(oct12.relativeToLargestMeasured2026EpisodePct,78.3);
 assert.equal(oct5.observedTimeCoveragePct,97.4);
 assert.equal(oct12.observedTimeCoveragePct,100);
 assert.equal(oct5.historicFacingSharePct,93.2);
 assert.equal(oct12.historicFacingSharePct,76.4);
 assert.equal(oct12.recordedWaveRebuild,true);
 assert.equal(oct5.recordedWaveRebuild,false);
 assert.ok(oct5.observedWaveActivityProxy>oct12.observedWaveActivityProxy);
 assert.equal(oct5.newRockExposureProbability,null);
 assert.equal(oct12.physicalPowerKWPerMeter,null);
});
test('all eight activity entries have independently measured original wave peaks, coverage and no safety predictions',()=>{
 assert.equal(source.entries.length,8);
 for(const e of source.entries){
  const original=season.rows.find(x=>x.peakObservedAt===e.peakAtUTC);
  assert.ok(original?.qualifyingOffshoreEpisode);
  assert.equal(e.peakSignificantHeightM,original.peakWaveHeightM);
  assert.equal(e.highestObservedWaveM,original.peakWaveHeightM);
  assert.ok(e.observedSampleCount>=6);
  assert.ok(e.observedTimeCoveragePct>=85);
  assert.ok(e.relativeToLargestMeasured2026EpisodePct<=100);
  assert.equal(e.enoughCoverageForRelativeComparison,true);
  assert.equal(e.physicalPowerKWPerMeter,null);
  assert.equal(e.calibratedBeachWaveHeightM,null);
  assert.equal(e.newRockExposureProbability,null);
  assert.equal(e.canPredictNewStones,false);
  assert.equal(e.canClaimSafeAccess,false);
 }
});
