'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const catalog=JSON.parse(read('data/up-waterfalls.json'));
const e=JSON.parse(read('data/up-waterfall-b77-wildcat-evidence.json'));
const guide=read('public/upper-peninsula-waterfalls/o-kun-de-kun-falls/index.html');
const hub=read('public/upper-peninsula-waterfalls/index.html');
const map=read('public/assets/up-fall-detail.js');
const sitemap=read('public/sitemap-up-waterfalls.xml');
test('B77 Konteka is a distinct approximate natural feature on an existing public journey, not an invented driving stop',()=>{
 const o=catalog.waterfalls.find(x=>x.id==='o-kun-de-kun-falls');
 assert.ok(o&&o.publication==='verified-access-guide');
 assert.equal(o.companionWaterfall.name,'Konteka Falls');
 assert.deepEqual([o.companionWaterfall.lat,o.companionWaterfall.lng],[46.64996,-89.15506]);
 assert.equal(o.companionWaterfall.sameUS45Trailhead,true);
 assert.equal(o.companionWaterfall.separateDrivingArrival,false);
 assert.equal(o.companionWaterfall.measuredRouteToFeature,false);
 assert.match(o.companionWaterfall.featurePositionRole,/not-parking/);
 assert.match(guide,/data-secondary-lat="46.64996" data-secondary-lng="-89.15506"/);
 assert.match(guide,/Konteka Falls/);
 assert.match(guide,/Peanut Butter Falls/);
 assert.match(guide,/1.4 miles one way/);
 assert.match(guide,/not a separate driving destination/i);
 assert.match(guide,/https:\/\/www.visitkeweenaw.com\/blog\/post\/a-fall-day-trip-to-o-kun-de-kun-falls\//);
 assert.match(guide,/https:\/\/www.waterfallsofthekeweenaw.com\/baltimore-river\/konteko-falls\//);
 assert.match(hub,/data-id="o-kun-de-kun-falls"/);
 assert.match(hub,/data-walk="About 1.4 miles one way/);
 assert.match(map,/secondarySource/);
 assert.match(map,/not a surveyed trail junction/);
 assert.ok(!catalog.waterfalls.some(x=>x.id==='konteka-falls'||x.id==='konteko-falls'));
 assert.ok(!sitemap.includes('/upper-peninsula-waterfalls/konteka-falls/'));
});
test('B77 Wildcat holds publication while exact feature-point role remains independent of owner arrival',()=>{
 assert.equal(e.method,'online-sources-only-no-outreach');
 assert.equal(e.access.landManager.verified,true);
 assert.equal(e.access.publicAccess.verified,true);
 assert.equal(e.access.parking.verified,true);
 assert.equal(e.access.trail.verified,true);
 assert.equal(e.access.location.verified,false);
 assert.equal(e.discrepancy.officialPositionWins,true);
 assert.equal(e.publicMapEligible,false);
 assert.equal(e.indexableGuideEligible,false);
 assert.equal(catalog.waterfalls.length,78);
 assert.equal((sitemap.match(/<loc>/g)||[]).length,76);
 assert.ok(!catalog.waterfalls.some(x=>x.id==='wildcat-falls'));
 assert.ok(!hub.includes('data-id="wildcat-falls"'));
 assert.ok(!sitemap.includes('/upper-peninsula-waterfalls/wildcat-falls/'));
 assert.ok(!fs.existsSync('public/upper-peninsula-waterfalls/wildcat-falls/index.html'));
});
