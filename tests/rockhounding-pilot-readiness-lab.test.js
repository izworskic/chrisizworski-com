'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {overallReadiness}=require('../lib/rockhounding/pilot-publication-readiness.cjs');
const frozen=require('../public/rockhounding-lab/pilot-readiness-2026.json');
const html=fs.readFileSync(path.join(__dirname,'../public/rockhounding-lab/index.html'),'utf8');
test('official township/EGLE source report used by noindex UI is deterministic from original inputs',()=>{
 assert.deepEqual(frozen,overallReadiness());
 assert.equal(frozen.schemaVersion,'rockhounding-grand-marais-publication-readiness-v1');
 assert.equal(frozen.townshipsPublicBeachSitesDocumented,2);
 assert.equal(frozen.sitesWithPublishedSpecificRockCollectingPermission,0);
 assert.equal(frozen.sitesWithValidatedLocalBreakingWaveMeasurements,0);
 assert.equal(frozen.sitesWithVerifiedStormToNewStoneOutcome,0);
 assert.equal(frozen.samplingQualifiedOriginalOffshoreEpisodeGroups,8);
 assert.equal(frozen.originalEGLEStateLandRule.thisNumberDoesNotAuthorizeTownshipCollection,true);
 assert.equal(frozen.canPublishCurrentBeachOpportunity,false);
});
test('two-site source panel visibly separates public visit information, collecting permission, wave conditions and stone proof',()=>{
 assert.match(html,/id="pilot-launch-readiness"/);
 assert.match(html,/id="pilot-launch-title"/);
 assert.match(html,/id="pilotReadinessProof"/);
 assert.match(html,/id="pilotReadinessPriority"/);
 assert.match(html,/pilot-readiness-2026\.json/);
 assert.match(html,/Two Grand Marais beaches. Very different evidence./);
 assert.match(html,/Bayshore Park/);
 assert.match(html,/Agate Beach/);
 assert.match(html,/5,243 regional offshore readings/);
 assert.match(html,/Burt Township documents/);
 assert.match(html,/municipal|township/i);
 assert.match(html,/25-pound annual limit/);
 assert.match(html,/does <strong>not<\/strong> automatically grant permission/);
 assert.match(html,/Exact parking route/);
 assert.match(html,/No verified harbor data/);
 assert.match(html,/a same-view beach photo from just before the July 21/i);
 assert.match(html,/sitesWithPublishedSpecificRockCollectingPermission!==0/);
 assert.match(html,/sitesWithVerifiedStormToNewStoneOutcome!==0/);
 assert.match(html,/canPublishCurrentBeachOpportunity!==false/);
 assert.match(html,/currentNwsQueryRun!==false/);
});
test('pilot photos and accessibility are not sold as safe/current, and mobile layout inherits responsive grid',()=>{
 assert.match(html,/<div class="two" style="align-items:stretch;gap:16px;margin:16px 0">/);
 assert.doesNotMatch(html,/id="pilot-launch-readiness"[\s\S]{0,7000}grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/);
 assert.match(html,/No current surf, collecting clearance or rock-exposure claim/);
 assert.match(html,/no wave or photo status here is a current invitation to enter the water/);
 assert.match(html,/burttownshipacmi\.gov\/recreation\/agate-beach-lake-superior/);
 assert.match(html,/burttownshipacmi\.gov\/recreation\/bayshore-park-public-swimming-areas/);
 assert.match(html,/www\.michigan\.gov\/egle\/public\/learn\/geology\/rockhounding/);
 assert.match(html,/<meta name="robots" content="noindex,nofollow,noarchive">/);
 assert.doesNotMatch(html,/adsbygoogle|googlesyndication/);
});
