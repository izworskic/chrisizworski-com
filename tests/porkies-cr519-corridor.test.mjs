import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import {fileURLToPath} from "node:url";
import {graphAudit,distance} from "../lib/porkies/route-topology.mjs";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const read=f=>fs.readFileSync(path.join(root,f),"utf8");
const ledger=JSON.parse(read("public/porcupine-mountains/west-access-evidence.json"));
const geo=JSON.parse(read("public/porcupine-mountains/cr519-road-reference.geojson"));
const park=JSON.parse(read("public/porcupine-mountains/access-points.json"));
const html=read("public/porcupine-mountains/index.html");
const ui=read("public/assets/porkies-route-evidence.js");
const sandbox={module:{exports:{}},globalThis:{}};
vm.runInNewContext(read("public/assets/porkies-access-map.js"),sandbox);
const {eligibility}=sandbox.module.exports;
test("Wakefield Township calls CR 519 Presque Isle Road and 17 government lines form one geometric corridor",()=>{
 assert.equal(geo.type,"FeatureCollection");
 assert.equal(geo.features.length,17);
 assert.equal(ledger.stateRoadGIS.sourceFeatureIds.length,17);
 assert.deepEqual(geo.features.map(f=>f.properties.id),ledger.stateRoadGIS.sourceFeatureIds);
 assert.ok(geo.features.every(f=>f.properties.name==="Presque Isle Rd"&&f.properties.nfc===5&&f.properties.routingCertified===false));
 assert.match(ledger.townshipRoadNameSource.meaning,/County Road 519/);
 const stats=graphAudit(geo.features,5,"name");
 assert.equal(stats.componentCount,1,"Only the 17 specified road centerlines should be joined at real endpoints");
 assert.ok(stats.totalGeometryMiles>12&&stats.totalGeometryMiles<15);
 assert.equal(ledger.stateRoadGIS.heldSeparateWesternSideRoads.count,3);
 assert.equal(ledger.stateRoadGIS.heldSeparateWesternSideRoads.nfc,0);
 assert.match(ledger.stateRoadGIS.note,/signed junctions/);
});
test("GIS centerline stops over 1 km from DNR parking: never a complete routing network",()=>{
 const north=geo.features[0].geometry.coordinates.slice(-1)[0];
 const parking=park.points.find(p=>p.id==="presque");
 const off=distance(north,[parking.lon,parking.lat]);
 assert.ok(off>1200&&off<1500,off+" m gap to parking");
 assert.equal(ledger.stateRoadGIS.northEndGapToParkingMetersApprox,1316);
 assert.equal(ledger.routeRules.certifiedRoute,false);
 assert.equal(ledger.routeRules.driveTimeMinutes,null);
});
test("Dated M28/CR519 water-main closure does not imply full-road closure or an invented Johnson Road turn sequence",()=>{
 const n=ledger.temporaryNotice;
 assert.equal(n.publishedOn,"2026-09-22");
 assert.equal(n.reopeningVerified,false);
 assert.equal(n.explicitClosureEnd,null);
 assert.match(n.closureScope,/intersection/);
 assert.equal(n.publishedDetour,"Johnson Road");
 assert.equal(n.detourRouteVerifiedInRoadGraph,false);
 assert.equal(n.notATurnByTurnDetour,true);
 assert.equal(ledger.routeRules.uncheckedGoogleDirectionsAllowed,false);
 assert.match(n.source,/wakefieldtownship/);
 assert.match(html,/not<\/strong> prove that the whole road remains closed/);
});
test("Google driving URL is withheld for west parking after unresolved notice, yet location maps and other safe routes persist",()=>{
 const p=park.points.find(p=>p.id==="presque");
 assert.equal(p.westEntranceNotice.reopeningVerified,false);
 assert.equal(eligibility(p,"2026-10-28","west").canDirect,false);
 assert.equal(eligibility(p,"2027-01-15","west").canDirect,false);
 assert.equal(eligibility(p,"2026-08-15","west").canDirect,true);
 assert.match(eligibility(p,"2027-01-15","west").notice,/Johnson Road/);
 const lake=park.points.find(p=>p.id==="lake");
 assert.equal(eligibility(lake,"2026-08-15","east").canDirect,true);
 assert.match(html,/id="porkies-cr519-toggle"/);
 assert.match(ui,/cr519-road-reference.geojson/);
 assert.match(ui,/west-access-evidence.json/);
 assert.match(html,/noindex,follow/);
 assert.equal(geo.properties.routeCertified,false);
});
test("Gogebic County roadside nighttime restriction and roadway project timelines remain distinct",()=>{
 assert.match(ledger.overnightRoadsideParking.restriction,/November 1/);
 assert.match(ledger.overnightRoadsideParking.restriction,/2:00–7:00/);
 assert.match(html,/2 of 10/);
 assert.match(html,/not a current construction notice or closure/);
 assert.match(html,/water-main work-zone closure/);
});
