import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const root='public/upper-peninsula-waterfalls/';
const records=JSON.parse(fs.readFileSync('data/up-waterfalls.json','utf8')).waterfalls;
const rec=JSON.parse(fs.readFileSync('data/up-waterfall-reconciliation.json','utf8'));
const ledger=JSON.parse(fs.readFileSync('data/up-waterfall-inventory-ledger.json','utf8'));
const queue=JSON.parse(fs.readFileSync('data/up-waterfall-review-queue.json','utf8'));
const html=fs.readFileSync(root+'wright-street-falls/index.html','utf8');
const hub=fs.readFileSync(root+'index.html','utf8');
const sitemap=fs.readFileSync('public/sitemap-up-waterfalls.xml','utf8');
const mapJs=fs.readFileSync('public/assets/up-fall-detail.js','utf8');
const item=records.find(x=>x.id==='wright-street-falls');
test('Wright Street is source-backed public walking access, not a route to McClure gorge',()=>{
 assert.ok(item);
 assert.equal(item.publication,'verified-access-guide');
 assert.equal(item.lat,46.56588);assert.equal(item.lng,-87.44576);
 assert.ok(!('gisObjectId' in item));
 assert.match(item.access,/Travel Marquette/);
 assert.match(item.parking,/Wright Street/);
 assert.match(item.walk,/boardwalk/);
 assert.match(item.further,/McClure/);
 for(const k of ['landManager','publicAccess','parking','trail','location']){
  assert.equal(item.verification[k].verified,true,k);
  assert.match(item.verification[k].source,/^https:\/\//);
 }
 const dead=rec.candidates.find(x=>x.gisObjectId===160);
 assert.equal(dead.curatedId,null);
 assert.equal(dead.publicationEligible,false);
 assert.equal(dead.accessRouteAudit.outcome,'not-cleared');
 const au=rec.candidates.find(x=>x.gisObjectId===192);
 assert.equal(au.publicationEligible,false);
 const gabbro=rec.candidates.find(x=>x.gisObjectId===38);
 assert.equal(gabbro.publicationEligible,true);assert.equal(gabbro.curatedId,'gabbro-falls');
});
test('guide, sitemap, JSON-LD and map keep creator, location and discovery consistent',()=>{
 const url='https://chrisizworski.com/upper-peninsula-waterfalls/wright-street-falls/';
 assert.match(html,/<meta name="robots" content="index,follow/);
 assert.ok(html.includes('rel="canonical" href="'+url+'"'));
 assert.ok(html.includes('https://chrisizworski.com/#person'));
 assert.ok(html.includes('Built by'));
 assert.ok(!html.includes('data-parking-lat='));
 assert.ok(!html.includes('destination=46.56588'));
 assert.ok(!html.includes('data-visit-lat='));
 assert.match(html,/Dead River Falls/);
 const json=JSON.parse(html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
 assert.ok(json['@graph'].some(x=>x['@type']==='TouristAttraction'&&x.geo.latitude===46.56588));
 assert.ok(json['@graph'].some(x=>x['@type']==='Person'));
 assert.equal((sitemap.match(new RegExp(url.replaceAll('/','\\/'),'g'))||[]).length,1);
 assert.ok(hub.includes('data-id="wright-street-falls"'));
 assert.equal((hub.match(/<article class="waterfall-card"/g)||[]).length,76);
 const list=JSON.parse(hub.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1])['@graph'].find(x=>x['@type']==='ItemList');
 assert.equal(list.numberOfItems,74);
 assert.equal(list.itemListElement.find(x=>x.url===url).position,71);
 assert.equal(records.length,76);
 assert.equal(rec.counts.curatedTotal,76);assert.equal(rec.counts.curatedNoMatchingGIS,11);
 assert.equal(ledger.curatedCount,76);assert.equal(queue.counts.curatedDestinations,76);
 assert.equal(queue.candidates.length,92);
 assert.equal(rec.counts.exactIdMatched,69);
 assert.ok(mapJs.includes('/api/carto-basemap-config'));
 assert.ok(mapJs.includes('tile.openstreetmap.org'));
 assert.ok(!mapJs.includes("L.tileLayer('https://basemaps.cartocdn.com/light_all/"));
});
