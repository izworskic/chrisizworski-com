import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {spawnSync} from 'node:child_process';
const read=p=>fs.readFileSync(p,'utf8');
const cat=JSON.parse(read('data/up-waterfalls.json')).waterfalls;
const rec=JSON.parse(read('data/up-waterfall-reconciliation.json'));
const ledger=JSON.parse(read('data/up-waterfall-inventory-ledger.json'));
const queue=JSON.parse(read('data/up-waterfall-review-queue.json'));
const research=JSON.parse(read('public/assets/up-waterfall-access-reviews.json'));
const near=JSON.parse(read('public/assets/up-waterfalls-nearby.json'));
const hub=read('public/upper-peninsula-waterfalls/index.html');
const sitemap=read('public/sitemap-up-waterfalls.xml');
const guide=read('public/upper-peninsula-waterfalls/conglomerate-falls-gratiot/index.html');
const original=read('public/upper-peninsula-waterfalls/research/upper-gratiot-river-falls/index.html');
const kna='https://keweenawnaturalareas.org/KNA/Conglomerate_Falls.html';
const id='conglomerate-falls-gratiot',url='https://chrisizworski.com/upper-peninsula-waterfalls/'+id+'/';
const row=cat.find(x=>x.id===id);
const c=rec.candidates.find(x=>x.gisObjectId===136);
const l=ledger.entries.find(x=>x.source==='mi-state-gis'&&x.sourceId===136);
const v=research.records.find(x=>x.gisObjectId===136);

test('B64: landowner invitation, named road easement and season gate promote only the correct Gratiot feature',()=>{
 assert.ok(row&&c&&l&&v);
 assert.equal(cat.length,77);
 assert.equal(rec.counts.curatedTotal,77);
 assert.equal(rec.counts.exactIdMatched,69);
 assert.equal(rec.counts.pending,92);
 assert.equal(rec.counts.curatedNoMatchingGIS,12);
 assert.equal(ledger.curatedCount,77);
 assert.equal(ledger.linkedByExactOid,69);
 assert.equal(ledger.unresolvedCandidates,92);
 assert.equal(queue.candidates.length,92);
 assert.equal(near.counts.eligible,68);
 assert.equal(row.gisObjectId,136);
 assert.equal(c.curatedId,id);assert.equal(l.curatedId,id);
 assert.equal(c.publicGuide,'/upper-peninsula-waterfalls/'+id+'/');
 assert.equal(c.publicationEligible,true);assert.equal(l.publication,'verified-access-guide');
 assert.equal(c.accessRouteAudit.destinationCoordinatesForDriving,false);
 assert.equal(c.accessRouteAudit.routePolylineAuthorized,false);
 assert.equal(row.verification.landManager.source,kna);
 assert.equal(row.verification.parking.source,kna);
 assert.equal(row.verification.parking.verified,true);
 assert.match(row.parking,/easement/);
 assert.match(row.access,/spring thaw/);
 assert.match(row.sourceReviewed,/2026-11-03/);
 assert.ok(!queue.candidates.some(x=>x.gisObjectId===136));
 assert.equal(v.publicationEligible,true);
 assert.equal(v.routeAudit.destinationCoordinatesForDriving,false);
 assert.equal(v.routeAudit.routePolylineAuthorized,false);
 assert.match(v.summary,/easement/);
 const lower=rec.candidates.find(x=>x.gisObjectId===137);
 assert.equal(lower.curatedId,null,'Lower Gratiot must not inherit the Conglomerate route');
 assert.equal(lower.publicationEligible,false);
 assert.ok(queue.candidates.some(x=>x.gisObjectId===137));
 assert.ok(cat.some(x=>x.id==='great-conglomerate-falls'),'Black River falls must remain independent');
});

test('B64: public guide is discoverable exactly once and explains seasonal gate, no unsafe car or river routing',()=>{
 assert.match(guide,/name="robots" content="index,follow/);
 assert.match(guide,/rel="canonical" href="https:\/\/chrisizworski\.com\/upper-peninsula-waterfalls\/conglomerate-falls-gratiot\//);
 assert.match(guide,/name="author" content="Chris Izworski"/);
 assert.match(guide,/"@id":"https:\/\/chrisizworski\.com\/#person"/);
 assert.match(guide,/private property/);assert.match(guide,/easement/);
 assert.match(guide,/spring thaw/);
 assert.match(guide,/KNA's official/);
 assert.match(guide,/Lower Gratiot/);
 assert.match(guide,/Great Conglomerate Falls/);
 assert.match(guide,/Waterfall, not a car destination/);
 assert.ok(guide.includes(kna));
 assert.ok(!guide.includes('google.com/maps/dir/?api=1&destination=47.329239'));
 assert.ok(!guide.includes('data-parking-lat='));
 assert.equal((sitemap.match(new RegExp(url,'g'))||[]).length,1);
 assert.equal((sitemap.match(/<loc>/g)||[]).length,75);
 assert.match(hub,/data-id="conglomerate-falls-gratiot" data-gis-oid="136"/);
 assert.match(hub,/data-arrival-verified="verified"/);
 assert.match(hub,/77 curated visitor destinations/);
 assert.match(original,/noindex,follow/);
 assert.match(original,/OLDER “NOT CLEARED” ACCESS FINDING HAS BEEN SUPERSEDED/);
 assert.ok(original.includes('/upper-peninsula-waterfalls/conglomerate-falls-gratiot/'));
 assert.ok(!sitemap.includes('/research/upper-gratiot-river-falls/'));
 const jsonld=JSON.parse(hub.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1]);
 const list=jsonld['@graph'].find(x=>x['@type']==='ItemList');
 assert.equal(list.numberOfItems,75);
 assert.equal(list.itemListElement.filter(x=>x.url===url).length,1);
});

test('B64: source-verified nearby geographic index and research queue exactly regenerate',t=>{
 const nearResult=spawnSync('python3',['scripts/build-up-waterfalls-nearby.py','--check'],{encoding:'utf8'});
 if(nearResult.error?.code==='ENOENT')t.diagnostic('Python unavailable; Node B59 geometry cross-check continues');
 else assert.equal(nearResult.status,0,nearResult.stderr||nearResult.stdout);
 assert.deepEqual(near.locations.filter(x=>x.id===id).map(x=>x.source),[kna]);
 assert.ok(near.nearby[id]?.some(x=>x.id==='eagle-river-falls'));
 assert.ok(!near.locations.some(x=>x.id==='lower-gratiot-river-falls'));
 const q=spawnSync('node',['scripts/build-up-waterfall-review-queue.mjs','--check'],{encoding:'utf8'});
 assert.equal(q.status,0,q.stderr||q.stdout);
});
