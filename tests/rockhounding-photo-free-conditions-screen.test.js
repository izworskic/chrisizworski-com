 assert.match(html,/id="trend"/);
 assert.match(html,/id="levelChange"/);
 assert.match(html,/id="chart"/);
 assert.match(html,/id="memoryState"/);
 assert.match(html,/id="advisory"/);
 assert.match(html,/id="refresh"/);
 assert.match(html,/id="btn48"/);
 assert.match(html,/id="btn7"/);
 assert.match(html,/Bayshore Park lies in the harbor/);
 assert.match(html,/No photos or external map keys/);
 assert.doesNotMatch(html,/<img\b|adsbygoogle|googlesyndication|carto\.com|mapbox|<iframe/);
